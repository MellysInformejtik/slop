#!/usr/bin/env python3
"""Generate vdi_exports.cpp: the C entry points NEXT's composer service dlsym()s, forwarded to
OpenHarmony's DRM composer (DisplayComposerVdiImpl, drivers_peripheral composer/vdi_base).

usage: gen_exports.py ADAPTER_HEADER VDI_METHODS NEEDED_NAMES OUT.cpp
  ADAPTER_HEADER  drivers_interface .../display_vdi_adapter_interface.h (the XxxFunc typedefs)
  VDI_METHODS     names IDisplayComposerVdi implements (forwarded)
  NEEDED_NAMES    names NEXT's libdisplay_composer_service looks up (everything else is a stub)
"""
import re
import sys

hdr, methods_f, needed_f, out = sys.argv[1:]
text = open(hdr).read()
methods = set(open(methods_f).read().split())
needed = set(open(needed_f).read().split())

sigs = {}
for m in re.finditer(r'using (\w+)Func = int32_t \(\*\)\((.*?)\);', text, re.S):
    sigs[m.group(1)] = ' '.join(m.group(2).split())


def arg_names(params):
    names = []
    depth = 0
    cur = ''
    for ch in params + ',':
        if ch in '<(':
            depth += 1
        elif ch in '>)':
            depth -= 1
        if ch == ',' and depth == 0:
            p = cur.strip()
            if p:
                names.append(re.findall(r'(\w+)\s*$', p)[0])
            cur = ''
        else:
            cur += ch
    return names


lines = ['// Generated by gen_exports.py: do not edit.',
         '#include "vdi_exports.h"',
         '',
         'namespace OHOS::HDI::Display::Composer {',
         '']
names = sorted((needed | {'LoadVdiImpl', 'DestroyVdiImpl'}) & set(sigs) | (needed - set(sigs)))
for name in names:
    params = sigs.get(name)
    if name == 'LoadVdiImpl':
        body = 'return NegroniComposer() ? DISPLAY_SUCCESS : DISPLAY_FAILURE;'
    elif name == 'DestroyVdiImpl':
        body = 'return DISPLAY_SUCCESS;'
    elif params is not None and name in methods:
        body = f'return NegroniComposer()->{name}({", ".join(arg_names(params))});'
    else:
        body = f'NegroniStub("{name}"); return DISPLAY_NOT_SUPPORT;'
    if params is None:
        params = '...'          # Huawei-only entry point: signature unknown, never forwarded
    lines.append(f'extern "C" __attribute__((visibility("default"))) int32_t {name}({params})')
    lines.append(f'{{\n    {body}\n}}\n')
lines.append('} // namespace OHOS::HDI::Display::Composer')
open(out, 'w').write('\n'.join(lines) + '\n')
print(f'{len(names)} entry points, '
      f'{sum(1 for n in names if n in methods and n in sigs)} forwarded')
